const supabase = createClient(supabaseUrl, supabaseKey);

async function seed() {
  const { error } = await supabase.from("posts").upsert(
    articles.map((item) => ({
      ...item,
      article_type: "guide",
      published_at: new Date().toISOString(),
      status: "published",
    })),
    { onConflict: "slug" },
  );

  if (error) throw new Error(`فشل إدراج المقالات: ${error.message}`);
  console.log(`تم بنجاح إدراج أو تحديث ${articles.length} مقالًا تجريبيًا عبر 19 فرعًا.`);
}

seed().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
